"""Set up results_final/simulation/<prefix>_<level>/ for HMM BCV + NCV runs on the hmm_hrf noise / AR(1) sweeps.

Prefixes (datasets from examples/simulation/evaluation_paper.py):
- hmm_hrf_noise: hmm_hrf plus white measurement noise, level = noise-to-signal variance ratio
- hmm_ar1: HMM with AR(1) dynamics within states (no HRF), level = AR(1) coefficient
- hmm_ar1noise: HMM (no HRF) plus AR(1) measurement noise (coefficient 0.5), level = noise-to-signal variance ratio

For each level this writes:
- config_simulation.yaml: the hmm_hrf HMM training settings, data from
  data/node_timeseries/simulation_final/<prefix>_<level>/, K = 1..16, n_bcv BCV folds and n_ncv NCV folds
- bcv_partition/fold_indices_{1..n_bcv}.json and ncv_partition/fold_indices_{1..n_ncv}.json: copied from
  hmm_hrf (same 500 subjects x 50 channels layout), so the noise sweeps are paired fold by fold with hmm_hrf
- config_list.csv: the array index -> (model, K, mode) table that IndexParser would make
  (written here so that IndexParser does not draw new random partitions)

No data is read: only configs and partition indices.

Usage (from the repository root):
    python response_to_reviewers/make_hrf_noise_configs.py 0.25 1.0 4.0
    python response_to_reviewers/make_hrf_noise_configs.py --prefix hmm_ar1 0.5 0.8 0.95
    python response_to_reviewers/make_hrf_noise_configs.py --prefix hmm_ar1noise 0.25 1.0 4.0
"""

import argparse
import os
import shutil
from datetime import datetime, timezone
from itertools import product

import pandas as pd
import yaml

ROOT = "./results_final/simulation"
SRC = f"{ROOT}/hmm_hrf"
NOTES = {
    "hmm_hrf_noise": "hmm_hrf plus white measurement noise (noise-to-signal variance ratio {})",
    "hmm_ar1": "HMM with AR(1) dynamics within states (coefficient {}), no HRF, hmm_iid-type random covariances",
    "hmm_ar1noise": "HMM (no HRF, hmm_iid-type random covariances) plus AR(1) measurement noise, coefficient 0.5 "
                    "(noise-to-signal variance ratio {})",
}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("levels", nargs="+")
    parser.add_argument("--prefix", default="hmm_hrf_noise", choices=list(NOTES))
    parser.add_argument("--n_bcv", type=int, default=20)
    parser.add_argument("--n_ncv", type=int, default=5)
    args = parser.parse_args()

    with open(f"{SRC}/config_simulation.yaml") as f:
        original = yaml.safe_load(f)
    bcv, ncv = original["mode"]["bcv"], original["mode"]["ncv"]
    n_states = original["n_states"]

    for r in args.levels:
        name = f"{args.prefix}_{r}"
        dst = f"{ROOT}/{name}"
        if os.path.exists(dst):
            raise FileExistsError(f"{dst} already exists")

        config = {
            "header": {
                "time": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
                "note": NOTES[args.prefix].format(r) + f": hmm only, "
                        f"{args.n_bcv} bi-cross-validation splits, {args.n_ncv}-fold naive cross-validation",
            },
            "load_data": {**original["load_data"], "inputs": f"./data/node_timeseries/simulation_final/{name}/"},
            "save_dir": f"{dst}/",
            "spatial_map": original["spatial_map"],
            "model": {"hmm": original["model"]["hmm"]},
            "n_states": n_states,
            "mode": {
                "bcv": {
                    "split_row": {**bcv["split_row"], "method_kwargs": {**bcv["split_row"]["method_kwargs"], "n_splits": args.n_bcv}},
                    "split_column": {**bcv["split_column"], "method_kwargs": {**bcv["split_column"]["method_kwargs"], "n_splits": args.n_bcv}},
                    "strategy": bcv["strategy"],
                },
                "ncv": {"split_row": {**ncv["split_row"], "method_kwargs": {**ncv["split_row"]["method_kwargs"], "n_splits": args.n_ncv}}},
            },
        }

        for mode, n in [("bcv", args.n_bcv), ("ncv", args.n_ncv)]:
            os.makedirs(f"{dst}/{mode}_partition")
            for i in range(1, n + 1):
                shutil.copy(f"{SRC}/{mode}_partition/fold_indices_{i}.json", f"{dst}/{mode}_partition/")

        with open(f"{dst}/config_simulation.yaml", "w") as f:
            f.write(f"# Generated by response_to_reviewers/make_hrf_noise_configs.py from {SRC}/config_simulation.yaml\n")
            f.write(f"# BCV folds 1-{args.n_bcv} and NCV folds 1-{args.n_ncv} are copied from {SRC}.\n")
            yaml.safe_dump(config, f, default_flow_style=False, sort_keys=False)

        modes = [f"bcv_{i}" for i in range(1, args.n_bcv + 1)] + [f"ncv_{i}" for i in range(1, args.n_ncv + 1)]
        df = pd.DataFrame(list(product(["hmm"], n_states, modes)), columns=["model_index", "n_states", "mode_index"])
        df.to_csv(f"{dst}/config_list.csv", index=True)
        print(f"{dst}: {len(df)} jobs")


if __name__ == "__main__":
    main()
